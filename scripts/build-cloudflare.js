// 生成 Cloudflare Pages Functions 入口 functions/api/[[path]].js
// 复用 cloud-functions/api/_app.js 的零依赖 onRequest(context) → Response 逻辑，
// 并把 npc 价格与合成配方内联进来（同 EdgeOne 的 build-edgeone.js 思路）。
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const appSrc = fs.readFileSync(path.join(root, 'cloud-functions', 'api', '_app.js'), 'utf8');
const npcPricesJson = fs.readFileSync(path.join(root, 'data', 'npc-prices.json'), 'utf8');
const recipesJson = fs.readFileSync(path.join(root, 'data', 'recipes.json'), 'utf8');

const output = `// AUTO-GENERATED by scripts/build-cloudflare.js —— 勿手动修改（源码见 cloud-functions/api/_app.js）
// Cloudflare Pages Functions：catch-all [[path]].js 处理 /api/*；零依赖（fetch/Response/URL），npc 价格与合成配方已内联

// ---- NPC 价格（内联自 data/npc-prices.json）----
const npcPrices = ${npcPricesJson};

// ---- 合成配方（内联自 data/recipes.json）----
const recipes = ${recipesJson};

// ---- 应用逻辑（内联自 cloud-functions/api/_app.js）----
${appSrc}

export { onRequest };
`;

const outFile = path.join(root, 'functions', 'api', '[[path]].js');
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, output);
console.log('已生成', outFile, '(' + (output.length / 1024).toFixed(1) + ' KB)');
